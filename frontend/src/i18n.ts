export type Translations = {
  [K in keyof typeof strings['en']]: typeof strings['en'][K] extends (...args: infer A) => any
    ? (...args: A) => string
    : string
}

export const LANGUAGES = Object.keys(strings) as Lang[]

/** The raw string table for a language, exposed so tests can check every language has every key. */
export function rawStrings(lang: Lang): Record<string, unknown> {
  return strings[lang]
}

export function t(lang: Lang): Translations {
  // English fills any key a translation is missing, so the UI never renders "undefined".
  return { ...strings.en, ...(strings[lang] || {}) } as unknown as Translations
}
